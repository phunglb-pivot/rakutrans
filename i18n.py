class I18nManager:
    """Manages internationalization and string lookups."""
    def __init__(self, current_lang: str = "en"):
        self.current_lang = current_lang if current_lang in TRANSLATIONS else "en"

    def set_language(self, lang: str) -> None:
        if lang in TRANSLATIONS:
            self.current_lang = lang

    def t(self, key: str, **kwargs: Any) -> str:
        """Get translated string by key with format substitutions."""
        text = TRANSLATIONS.get(self.current_lang, {}).get(key)
        if text is None:
            # Fallback to English
            text = TRANSLATIONS.get("en", {}).get(key, key)
        if kwargs:
            try:
                return text.format(**kwargs)
            except Exception:
                return text
        return text
